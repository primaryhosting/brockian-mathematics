#!/usr/bin/env python3
"""CLI for the multi-domain problem attack pipeline.

Usage:
  python3 -m pipeline.scripts.pipeline_cli list [--domain D] [--status S]
  python3 -m pipeline.scripts.pipeline_cli show ID
  python3 -m pipeline.scripts.pipeline_cli triage ID
  python3 -m pipeline.scripts.pipeline_cli queue [--limit N]
  python3 -m pipeline.scripts.pipeline_cli attempt ID --mode M --result R [--note ...]
  python3 -m pipeline.scripts.pipeline_cli distill-check PATH
  python3 -m pipeline.scripts.pipeline_cli ledger
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Allow `python3 -m pipeline.scripts.pipeline_cli` from repo root
_REPO = Path(__file__).resolve().parents[2]
if str(_REPO) not in sys.path:
    sys.path.insert(0, str(_REPO))

from pipeline.core.ledger import registry_evidence_for_cards, summarize_ledger  # noqa: E402
from pipeline.core.schema import find_card, load_catalog, save_card  # noqa: E402
from pipeline.core.stages import decompose_stub, record_attempt, triage  # noqa: E402
from pipeline.core.triage import build_attack_queue  # noqa: E402
from pipeline.distill.score import check_cheatsheet  # noqa: E402

LEDGER_DIR = Path(__file__).resolve().parents[1] / "ledger"
REGISTRY_PATH = _REPO / "registry" / "theorems.json"


def cmd_list(args: argparse.Namespace) -> int:
    cards = load_catalog(domain=args.domain, status=args.status)
    if not cards:
        print("(no problems match)")
        return 0
    for c in sorted(cards, key=lambda x: (-x.priority, x.id)):
        tags = ",".join(c.tags[:4])
        print(f"{c.id:28} {c.domain:12} {c.status:12} d={c.difficulty} p={c.priority:3}  {c.title[:50]}  [{tags}]")
    print(f"\n{len(cards)} problem(s)")
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    card, path = find_card(args.id)
    print(json.dumps(card.to_dict(), indent=2, ensure_ascii=False))
    print(f"\n# path: {path}", file=sys.stderr)
    return 0


def cmd_triage(args: argparse.Namespace) -> int:
    card, _ = find_card(args.id)
    plan = triage(card)
    decomp = decompose_stub(card)
    out = {"triage": plan, "decompose": decomp}
    print(json.dumps(out, indent=2, ensure_ascii=False))
    return 0


def cmd_queue(args: argparse.Namespace) -> int:
    cards = load_catalog(domain=args.domain)
    queue = build_attack_queue(cards, limit=args.limit)
    for i, p in enumerate(queue, 1):
        print(f"{i:2}. {p['id']:28} yield={p['yield_score']:3}  {p['status']:12}  modes={','.join(p['recommended_modes'][:4])}")
        if p.get("warnings"):
            for w in p["warnings"]:
                print(f"     ! {w}")
    return 0


def cmd_attempt(args: argparse.Namespace) -> int:
    card, path = find_card(args.id)
    card, reg = record_attempt(
        card,
        mode=args.mode,
        result=args.result,
        note=args.note or "",
        agent=args.agent,
        artifacts=args.artifact or [],
        axle_verified=True if args.axle_verified else (False if args.axle_failed else None),
        axioms_clean=bool(args.axioms_clean),
    )
    save_card(card, path)
    print(f"recorded attempt → status={card.status} register={reg}")
    print(f"saved {path}")
    return 0


def cmd_distill_check(args: argparse.Namespace) -> int:
    report = check_cheatsheet(
        args.path,
        accuracy=args.accuracy,
        min_accuracy=args.min_accuracy,
    )
    print(json.dumps(report, indent=2))
    return 0 if report.get("ok") else 1


def cmd_ledger(args: argparse.Namespace) -> int:
    cards = load_catalog()
    registry_payload = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    registry_by_id = registry_evidence_for_cards(cards, registry_payload)
    rows = summarize_ledger(cards, registry_by_id=registry_by_id)
    LEDGER_DIR.mkdir(parents=True, exist_ok=True)
    json_path = LEDGER_DIR / "problems.json"
    md_path = LEDGER_DIR / "LEDGER.md"
    payload = {
        "count": len(rows),
        "by_register": _count_by(rows, "register"),
        "by_domain": _count_by(rows, "domain"),
        "problems": rows,
    }
    json_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    md = _render_md(payload)
    md_path.write_text(md, encoding="utf-8")
    print(f"wrote {json_path}")
    print(f"wrote {md_path}")
    print(f"count={payload['count']} registers={payload['by_register']}")
    return 0


def _count_by(rows: list[dict], key: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for r in rows:
        k = str(r.get(key, "?"))
        out[k] = out.get(k, 0) + 1
    return dict(sorted(out.items(), key=lambda kv: (-kv[1], kv[0])))


def _render_md(payload: dict) -> str:
    lines = [
        "# Problem Attack Pipeline Ledger",
        "",
        "> Generated by `python3 -m pipeline.scripts.pipeline_cli ledger`.",
        "> Register is **derived** from card facts + attempts (never hand-assert PROVED without AXLE).",
        "",
        f"**Total problems:** {payload['count']}",
        "",
        "## By register",
        "",
        "| Register | Count |",
        "|---|---|",
    ]
    for k, v in payload["by_register"].items():
        lines.append(f"| {k} | {v} |")
    lines += [
        "",
        "## By domain",
        "",
        "| Domain | Count |",
        "|---|---|",
    ]
    for k, v in payload["by_domain"].items():
        lines.append(f"| {k} | {v} |")

    registry_issues = []
    for row in payload["problems"]:
        verification = row.get("verification") or {}
        for ref in verification.get("missing_registry_refs") or []:
            registry_issues.append((row["id"], "missing", ref))
        for ref in verification.get("unverified_registry_refs") or []:
            registry_issues.append((row["id"], "unverified", ref))
    if registry_issues:
        lines += [
            "",
            "## Registry reference issues",
            "",
            "> Missing or unverified theorem refs block registry-backed PROVED promotion.",
            "",
            "| ID | Issue | Theorem reference |",
            "|---|---|---|",
        ]
        for problem_id, issue, ref in registry_issues:
            lines.append(f"| `{problem_id}` | {issue} | `{ref}` |")

    lines += [
        "",
        "## Problems",
        "",
        "| Register | ID | Domain | Status | Diff | Pri | Title |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in payload["problems"]:
        title = (r.get("title") or "").replace("|", "\\|")[:60]
        lines.append(
            f"| {r['register']} | `{r['id']}` | {r['domain']} | {r['status']} "
            f"| {r.get('difficulty')} | {r.get('priority')} | {title} |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Multi-domain problem attack pipeline")
    sub = p.add_subparsers(dest="cmd", required=True)

    sp = sub.add_parser("list", help="List problems")
    sp.add_argument("--domain", choices=["erdos", "distillation", "sair", "math", "physics", "cs", "quantum"])
    sp.add_argument("--status")
    sp.set_defaults(func=cmd_list)

    sp = sub.add_parser("show", help="Show one problem card as JSON")
    sp.add_argument("id")
    sp.set_defaults(func=cmd_show)

    sp = sub.add_parser("triage", help="Triage + decompose plan")
    sp.add_argument("id")
    sp.set_defaults(func=cmd_triage)

    sp = sub.add_parser("queue", help="Ranked attack queue")
    sp.add_argument("--domain")
    sp.add_argument("--limit", type=int, default=20)
    sp.set_defaults(func=cmd_queue)

    sp = sub.add_parser("attempt", help="Record an attack attempt")
    sp.add_argument("id")
    sp.add_argument("--mode", required=True)
    sp.add_argument("--result", required=True)
    sp.add_argument("--note", default="")
    sp.add_argument("--agent", default="human")
    sp.add_argument("--artifact", action="append", default=[])
    axle_group = sp.add_mutually_exclusive_group()
    axle_group.add_argument("--axle-verified", action="store_true")
    axle_group.add_argument("--axle-failed", action="store_true")
    sp.add_argument("--axioms-clean", action="store_true")
    sp.set_defaults(func=cmd_attempt)

    sp = sub.add_parser("distill-check", help="Check cheatsheet size/accuracy gates")
    sp.add_argument("path")
    sp.add_argument("--accuracy", type=float, default=None)
    sp.add_argument("--min-accuracy", type=float, default=None)
    sp.set_defaults(func=cmd_distill_check)

    sp = sub.add_parser("ledger", help="Rebuild pipeline/ledger artifacts")
    sp.set_defaults(func=cmd_ledger)

    args = p.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())

"""Generate the Markdown theorem table used by the paper appendix.

Input:
  registry/theorems.json

Output:
  paper/theorem_table.md

The default table includes claim-bearing registry entries only:
PROVED, CONDITIONAL, and CONJECTURE. Definitions can be included with
--include-definitions when an API appendix is wanted.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REGISTRY = ROOT / "registry" / "theorems.json"
DEFAULT_OUTPUT = ROOT / "paper" / "theorem_table.md"

REGISTER_ORDER = {
    "PROVED": 0,
    "CONDITIONAL": 1,
    "CONJECTURE": 2,
    "DEFINITION": 3,
}


def md_cell(value: Any) -> str:
    """Escape a compact value for one Markdown table cell."""
    text = "" if value is None else str(value)
    text = " ".join(text.split())
    return text.replace("\\", "\\\\").replace("|", "\\|")


def short_name(name: str) -> str:
    return name.split(".")[-1]


def short_note(note: str, limit: int) -> str:
    note = " ".join((note or "").split())
    if len(note) <= limit:
        return note
    return note[: max(0, limit - 1)].rstrip() + "..."


def axiom_status(entry: dict[str, Any]) -> str:
    verification = entry.get("verification") or {}
    if verification.get("axioms_ok") is True:
        return "clean"
    if verification.get("axioms_ok") is False:
        axioms = entry.get("axioms") or []
        return "not clean" if not axioms else "not clean: " + ", ".join(map(str, axioms))
    return "unknown"


def axle_env(entry: dict[str, Any]) -> str:
    axle = ((entry.get("verification") or {}).get("axle") or {})
    env = axle.get("environment")
    verdict = axle.get("verdict")
    if env and verdict:
        return f"{env} ({verdict})"
    return env or verdict or "unknown"


def selected_entries(registry: dict[str, Any], include_definitions: bool) -> list[dict[str, Any]]:
    allowed = {"PROVED", "CONDITIONAL", "CONJECTURE"}
    if include_definitions:
        allowed.add("DEFINITION")
    entries = [t for t in registry.get("theorems", []) if t.get("register") in allowed]
    entries.sort(
        key=lambda t: (
            REGISTER_ORDER.get(t.get("register", ""), 99),
            t.get("module", ""),
            t.get("name", ""),
        )
    )
    return entries


def render_table(
    registry: dict[str, Any],
    entries: list[dict[str, Any]],
    note_limit: int,
    registry_path: Path,
) -> str:
    summary = registry.get("summary") or {}
    generated_from = registry.get("generated_from", "registry/theorems.json")
    registers = ["PROVED", "CONDITIONAL", "CONJECTURE", "DEFINITION"]
    summary_bits = ", ".join(f"{r}: {summary.get(r, 0)}" for r in registers if summary.get(r, 0))

    lines = [
        "# Paper Theorem Table",
        "",
        "<!-- Generated by scripts/gen_paper_theorem_table.py; do not edit by hand. -->",
        "",
        f"Input: `{registry_path}`",
        "",
        f"Registry generated from: `{generated_from}`",
        "",
        f"Registry summary: {summary_bits}.",
        "",
        f"Rows emitted: {len(entries)}.",
        "",
        "| Name | Register | Kind | Module | AXLE env | Axioms | Provenance |",
        "|---|---:|---|---|---|---|---|",
    ]

    for entry in entries:
        row = [
            f"`{md_cell(short_name(entry.get('name', '')))}`",
            md_cell(entry.get("register", "")),
            md_cell(entry.get("kind", "")),
            f"`{md_cell(entry.get('module', ''))}`",
            md_cell(axle_env(entry)),
            md_cell(axiom_status(entry)),
            md_cell(short_note(entry.get("provenance_note", ""), note_limit)),
        ]
        lines.append("| " + " | ".join(row) + " |")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--include-definitions",
        action="store_true",
        help="Include DEFINITION rows as well as claim-bearing rows.",
    )
    parser.add_argument(
        "--note-limit",
        type=int,
        default=120,
        help="Maximum characters kept from each provenance note.",
    )
    args = parser.parse_args()

    registry = json.loads(args.registry.read_text())
    entries = selected_entries(registry, args.include_definitions)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_table(registry, entries, args.note_limit, args.registry))
    print(f"wrote {args.output} ({len(entries)} rows)")


if __name__ == "__main__":
    main()
